"""Reproducible data-profiling script.

Produces outputs/data_profile.md and builds the processed Parquet tables.
Run: python profile_data.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from src import config as C
from src import ingestion, scenarios as S
from src.validation import dataset_summary, validate


def main() -> None:
    C.OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)
    raw = ingestion.load_raw()
    summary = dataset_summary(raw)
    report = validate(raw)

    lines: list[str] = ["# PocketShift AI — Data Profile", ""]
    lines.append("Generated by `profile_data.py`. All counts measured from the "
                 "workspace dataset.\n")

    # 1. Rows/cols per file.
    lines.append("## 1. Files")
    lines.append("| file | rows | columns |")
    lines.append("|---|---:|---:|")
    for name, df in (
        ("games", raw.games),
        ("plays", raw.plays),
        ("players", raw.players),
        ("pffScoutingData", raw.pff),
    ):
        lines.append(f"| {name} | {len(df):,} | {df.shape[1]} |")
    n_track = len(list(C.TRACKING_DIR.glob("tracking_*.csv"))) if C.TRACKING_DIR.exists() else 0
    lines.append(f"\nTracking files present: **{n_track}** (optional; app runs without them).\n")

    # 2. Validation.
    lines.append("## 2. Join & integrity checks")
    lines.append("| check | passed | detail |")
    lines.append("|---|:--:|---|")
    for c in report.checks:
        lines.append(f"| {c.name} | {'✅' if c.passed else '❌'} | {c.detail} |")
    lines.append(f"\n**All checks passed: {report.ok}**\n")

    # 3. Entity counts.
    lines.append("## 3. Unique entities")
    lines.append(f"- Games: {summary['n_games']}")
    lines.append(f"- Plays: {summary['n_plays']:,}")
    lines.append(f"- Players: {summary['n_players']:,}")
    lines.append(f"- Teams: {summary['n_teams']}")
    lines.append(f"- PFF rows: {summary['n_pff_rows']:,}\n")

    # 4. Role distribution.
    lines.append("## 4. PFF role distribution (normalised)")
    lines.append("| role | rows |")
    lines.append("|---|---:|")
    for k, v in sorted(summary["role_counts"].items(), key=lambda x: -x[1]):
        lines.append(f"| {k} | {v:,} |")
    lines.append("")

    # 5. Pass outcomes.
    lines.append("## 5. Pass-outcome distribution (passResult)")
    pr = raw.plays["passResult"].value_counts(dropna=False)
    lines.append("| result | n |")
    lines.append("|---|---:|")
    for k, v in pr.items():
        lines.append(f"| {k if pd.notna(k) else 'NA'} | {v:,} |")
    lines.append("")

    # 6. Coverage distribution.
    lines.append("## 6. Pass-coverage distribution (pff_passCoverage)")
    cov = raw.plays["pff_passCoverage"].value_counts(dropna=False).head(15)
    lines.append("| coverage | n |")
    lines.append("|---|---:|")
    for k, v in cov.items():
        lines.append(f"| {k if pd.notna(k) else 'NA'} | {v:,} |")
    lines.append("")

    # Build processed tables.
    tables = ingestion.build_processed(raw)
    paths = ingestion.write_processed(tables)
    pe = tables.plays_enriched

    # 7-9. Pressure / block / participation.
    lines.append("## 7. Pressure events (play-level proxy)")
    lines.append(f"- Pressure-event rate: **{pe['pressure_event'].mean():.1%}** "
                 f"({int(pe['pressure_event'].sum()):,} / {len(pe):,} plays)")
    lines.append(f"- Sack-event rate: **{pe['sack_event'].mean():.1%}**")
    lines.append(f"- Mean rushers/play: {pe['n_rushers'].mean():.2f} · "
                 f"mean blockers/play: {pe['n_blockers'].mean():.2f}\n")

    lines.append("## 8. Block-type frequency")
    bt = raw.pff["pff_blockType"].dropna().value_counts().head(12)
    lines.append("| block type | n |")
    lines.append("|---|---:|")
    for k, v in bt.items():
        lines.append(f"| {k} | {v:,} |")
    lines.append("")

    lines.append("## 9. Player participation")
    pp = raw.pff.groupby("nflId")["playId"].count()
    lines.append(f"- Players with charted plays: {pp.shape[0]:,}")
    lines.append(f"- Median charted plays/player: {int(pp.median())}")
    lines.append(f"- Max charted plays (one player): {int(pp.max())}\n")

    # 10. Scenario support.
    lines.append("## 10. Counterfactual scenario support")
    for scen in S.SCENARIOS:
        res = S.compare_protection_configurations(pe, scen)
        lines.append(f"- **{S.SCENARIOS[scen]['label']}** (whole dataset): "
                     f"supported={res.supported}, "
                     f"arm n = {res.arm_a['n']} / {res.arm_b['n']}")
    lines.append("")

    lines.append("## Processed outputs")
    for k, v in paths.items():
        try:
            rel = Path(v).relative_to(C.ROOT)
        except ValueError:
            rel = Path(v).name
        lines.append(f"- `{k}` → `{rel}`")

    # 11. Tracking-derived energy/fatigue (optional).
    import sys

    build_tracking = "--tracking" in sys.argv
    try:
        from src import tracking as TR

        if TR.tracking_available():
            lines.append("## 11. Tracking energy & fatigue (optional)")
            if build_tracking:
                n = None
                for a in sys.argv:
                    if a.startswith("--max-games="):
                        n = int(a.split("=")[1])
                pe, fat = TR.build_effort_tables(max_games=n or 12)
                TR.write_effort_tables(pe, fat)
                lines.append(
                    f"- Built energy tables: {len(pe):,} player-plays across "
                    f"{pe['gameId'].nunique()} game(s)."
                )
                lines.append(
                    f"- Fatigue-flagged player-games (>=10% late accel decline, "
                    f">=15 snaps): {int(fat['fatigue_flag'].sum())} / {len(fat)}."
                )
            else:
                lines.append(
                    f"- {len(TR._tracking_files())} tracking files present. "
                    "Run `python profile_data.py --tracking` to build energy tables."
                )
            lines.append("")
    except Exception as exc:  # noqa: BLE001
        lines.append(f"## 11. Tracking (skipped: {exc})\n")

    out = C.OUTPUTS_DIR / "data_profile.md"
    out.write_text("\n".join(lines))
    print(f"Wrote {out}")
    print(f"All validation checks passed: {report.ok}")


if __name__ == "__main__":
    main()
